import 'bible_library.dart';

class ReadingPlanDef {
  const ReadingPlanDef({
    required this.key,
    required this.name,
    required this.sub,
    required this.totalDays,
    required this.bookSelector,
  });

  final String key;
  final String name;
  final String sub;
  final int totalDays;

  /// Which books (in reading order) this plan covers, resolved against the
  /// loaded library so chapter counts always match the real text.
  final List<String> Function(BibleLibrary) bookSelector;
}

